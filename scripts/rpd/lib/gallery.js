function zoomScript() {
  // Tiny click-to-zoom. URLs stay on data-full / src — never concatenated
  // into a JS string from the manifest.
  return `<script>
(function () {
  var ov = document.getElementById('seed-zoom');
  if (!ov) return;
  var img = ov.querySelector('img');
  document.addEventListener('click', function (e) {
    var t = e.target;
    if (!t) return;
    if (t.classList && (t.classList.contains('seed-img') || t.classList.contains('seed-ref'))) {
      e.preventDefault();
      img.src = t.getAttribute('data-full') || t.src;
      ov.hidden = false;
      return;
    }
    if (t.id === 'seed-zoom' || (t.classList && t.classList.contains('seed-zoom-close'))) {
      ov.hidden = true;
      img.removeAttribute('src');
    }
  });
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') { ov.hidden = true; img.removeAttribute('src'); }
  });
})();
</script>`;
}

