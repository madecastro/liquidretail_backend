// ── data helpers ────────────────────────────────────────────────────────────

function unionModels(spec, cells) {
  const listed = Array.isArray(spec.models) ? spec.models.filter(Boolean).map(String) : [];
  const seen = new Set(listed);
  for (const c of cells) {
    if (c.model && !seen.has(c.model)) {
      listed.push(String(c.model));
      seen.add(c.model);
    }
  }
  return listed;
}

function unionVariants(spec, cells) {
  const listed = Array.isArray(spec.variants)
    ? spec.variants.filter(isObj).map((v) => ({ ...v, id: str(v.id) || '(none)' }))
    : [];
  const seen = new Set(listed.map((v) => v.id));
  for (const c of cells) {
    const id = str(c.variantId) || '(none)';
    if (!seen.has(id)) {
      listed.push({ id });
      seen.add(id);
    }
  }
  return listed;
}

function indexCells(cells) {
  const map = new Map();
  for (const c of cells) {
    const key = cellKey(c.model, str(c.variantId) || '(none)');
    if (!map.has(key)) map.set(key, c);
  }
  return map;
}

function cellKey(model, variantId) {
  return `${model || ''}\0${variantId || ''}`;
}

function tally(cells) {
  const byStatus = Object.fromEntries(STATUSES.map((s) => [s, 0]));
  let other = 0;
  let settled = 0;
  let estRemainder = 0;
  for (const c of cells) {
    const st = str(c.status);
    if (STATUSES.includes(st)) byStatus[st] += 1;
    else other += 1;
    if (c.costSource === 'actual' && Number.isFinite(Number(c.costUsd))) {
      settled += Number(c.costUsd);
    } else {
      const rem = firstFinite(c.estUsd, c.costUsd);
      if (Number.isFinite(rem)) estRemainder += rem;
    }
  }
  return {
    settled: fmtUsd(settled) || '0.00',
    estRemainder: fmtUsd(estRemainder) || '0.00',
    byStatus,
    other
  };
}

function pickVideoSrc(cell, runDir) {
  const raw = firstStr(cell.titledPath, cell.localPath);
  if (!raw) return '';
  return toRelative(raw, runDir);
}

function toRelative(p, runDir) {
  const s = String(p).trim();
  if (!s) return '';
  // Remote URLs would play locally but are not Pages-deployable and expire.
  // A mid-run rebuild with only videoUrl set must not silently ship a
  // gallery that dies after the prediction is gone.
  if (/^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(s)) return '';
  if (path.isAbsolute(s) && runDir) {
    const rel = path.relative(runDir, s);
    if (rel && !rel.startsWith('..') && !path.isAbsolute(rel)) {
      return rel.split(path.sep).join('/');
    }
    return '';
  }
  return s.replace(/\\/g, '/').replace(/^\.\//, '');
}

function normalizeRefs(refs) {
  if (!Array.isArray(refs)) return [];
  const out = [];
  for (const r of refs) {
    if (typeof r === 'string' && r.trim()) out.push(r.trim());
    else if (isObj(r) && str(r.url)) out.push(str(r.url));
  }
  return out;
}

function normalizeLever(lever) {
  const s = str(lever).toLowerCase();
  return LEVERS.includes(s) ? s : s || '';
}

function shortModel(model) {
  const s = String(model || '');
  const i = s.lastIndexOf('/');
  return i >= 0 ? s.slice(i + 1) : s;
}

function formatDuration(sec) {
  const n = Number(sec);
  if (!Number.isFinite(n)) return '—';
  return `${n}s`;
}

function formatLatency(ms) {
  const n = Number(ms);
  if (!Number.isFinite(n)) return '';
  return `${(n / 1000).toFixed(1)}s`;
}

function formatWhen(v) {
  if (v == null || v === '') return '';
  if (v instanceof Date && !Number.isNaN(v.getTime())) return v.toISOString();
  return String(v);
}

function fmtUsd(n) {
  const x = Number(n);
  if (!Number.isFinite(x)) return null;
  return x.toFixed(2);
}

function firstFinite(...vals) {
  for (const v of vals) {
    const n = Number(v);
    if (Number.isFinite(n)) return n;
  }
  return undefined;
}

function firstStr(...vals) {
  for (const v of vals) {
    if (v != null && String(v).trim()) return String(v).trim();
  }
  return '';
}

function safeHex(h) {
  if (typeof h !== 'string') return '';
  const s = h.trim();
  return /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(s) ? s : '';
}

function isObj(v) {
  return !!v && typeof v === 'object' && !Array.isArray(v);
}

function str(v) {
  if (v == null) return '';
  return String(v);
}

// Escape every manifest-derived string. Used for both text and quoted
// attributes — attribute context still needs quotes in the template.
function esc(v) {
  return String(v == null ? '' : v)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const escAttr = esc;

